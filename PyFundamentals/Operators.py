# Operators in Python
# Operators are special symbols that perform operations on variables and values. Python supports a wide range of operators, which can be categorized as follows:
# 1. Arithmetic Operators: These operators are used to perform mathematical operations like addition, subtraction, multiplication, division, etc.
# 2. Comparison Operators: These operators are used to compare two values and return a boolean result (True or False).
# 3. Logical Operators: These operators are used to combine conditional statements and return a boolean result.
# 4. Assignment Operators: These operators are used to assign values to variables.
# 5. Membership Operators: These operators are used to test whether a value is a member of a sequence (like a list, tuple, or string).
# 6. Identity Operators: These operators are used to compare the memory locations of two objects.


# # eg. of each type of operator:
# print(10+5)  # Output: 15 (Arithmetic Operator)
# print(10>5)   # Output: True (Comparison Operator)
# print(10==5)  # Output: False (Comparison Operator)
# x = 5  # Output: 5 (Assignment Operator)
# print(5 in [1, 2, 3, 4, 5])  # Output: True (Membership Operator)
# print(5 is 5)  # Output: True (Identity Operator)

# Summary of Operators in Python:
# - Arithmetic Operators: +, -, *, /, %, **
# - Comparison Operators: ==, !=, >, <, >=, <=
# - Logical Operators: and, or, not
# - Assignment Operators: =, +=, -=, *=, /=, %=
# - Membership Operators: in, not in
# - Identity Operators: is, is not