# If-Else Conditional Statements
# If-Else statements are used to make decisions in the program based on certain conditions.
# The 'if' block is executed if the condition is true, otherwise the 'else' block is executed.

x = 10
if x > 5:
    print("x is greater than 5")
else:
    print("x is not greater than 5")

# You can also use 'elif' (else if) to check multiple conditions.
y = 15
if y < 10:
    print("y is less than 10")
elif y == 10:
    print("y is equal to 10")
else:
    print("y is greater than 10")
