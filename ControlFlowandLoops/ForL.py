# for loops in Python
# A for loop is used to iterate over a sequence (like a list, tuple, dictionary, set, or string) and execute a block of code for each item in the sequence.
# The syntax of a for loop is as follows:
"""
for item in sequence:
    # Code to execute for each item
"""
# Example of a for loop iterating over a list
# numbers = [1, 2, 3, 4, 5]
# for num in numbers:
#     print(num)

# Using the range() function to generate a sequence of numbers
for i in range(5):  # This will iterate from 0 to 4
    print(i)
