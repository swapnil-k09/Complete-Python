# Variables and Data Types in Python

# Variables:
# In Python, you don't need to declare the type of a variable when you create it.
# The type is determined automatically based on the value assigned.
# x = 5  # x is an integer
# y = "John"  # y is a string
# z = 3.14  # z is a float

# Data Types:
# Python has several built-in data types:
# - Numeric Types: int, float, complex
# - Text Type: str
# - Boolean Type: bool
# - Sequence Types: list, tuple, range
# - Mapping Type: dict
# - Set Types: set, frozenset
# - Binary Types: bytes, bytearray, memoryview


# Checking the data type of a variable can be done using the type() function:
# eg,
# x = 5
# y = 14.5
# z = "Hello"
# print(type(x))  # Output: <class 'int'>
# print(type(y))  # Output: <class 'float'>
# print(type(z))  # Output: <class 'str'>