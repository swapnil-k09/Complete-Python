# Comments, Escape Sequences & Print Statement

# Commnets:
# In Python, comments are used to explain the code and make it more readable. Comments are ignored by the Python interpreter and do not affect the execution of the program. There are two types of comments in Python:
# 1. Single-line comments: These comments start with a hash symbol (#) and extend to the end of the line. They are used for brief explanations or notes.
# 2. Multi-line comments: These comments are enclosed within triple quotes (''' or """). They can span multiple lines and are used for longer explanations or documentation.
#eg,
# This is a single-line comment

'''
This is a multi-line comment.
It can span multiple lines.
'''

# Escape Sequences:
# Escape sequences are special characters that are used to represent certain characters in a string. They are preceded by a backslash (\) and have specific meanings. Some common escape sequences in Python include:
# - \n: Newline
# - \t: Tab
# - \\: Backslash
# - \': Single quote
# - \": Double quote
#eg,
# print("Hello\nWorld")  # Output: Hello (newline) World
# print("Hello\tWorld")  # Output: Hello (tab) World
# print("Hello\\World")  # Output: Hello\World
# print("Hello\'World")  # Output: Hello'World
# print("Hello\"World")  # Output: Hello"World

